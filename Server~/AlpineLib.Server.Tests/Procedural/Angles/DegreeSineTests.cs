        [Fact]
        public void EveryWholeDegreeMatchesTheGameTableBitForBit() {
            for (int degrees = 0; degrees < 360; degrees++) {
                DegreeSine.SinCos(degrees, out double sine, out double cosine);
                Assert.Equal(GameBits[degrees * 2], (ulong)BitConverter.DoubleToInt64Bits(sine));
                Assert.Equal(GameBits[degrees * 2 + 1], (ulong)BitConverter.DoubleToInt64Bits(cosine));
            }
        }

        [Theory]
        [InlineData(360)]
        [InlineData(-360)]
        [InlineData(720)]
        [InlineData(-1)]
        [InlineData(-359)]
        [InlineData(361)]
        [InlineData(-725)]
        [InlineData(1000003)]
        [InlineData(int.MaxValue)]
        [InlineData(int.MinValue)]
        public void OutOfTurnDegreesWrapToTheirTurn(int degrees) {
            int wrapped = (int)(((long)degrees % 360 + 360) % 360);
            DegreeSine.SinCos(degrees, out double sine, out double cosine);
            DegreeSine.SinCos(wrapped, out double expectedSine, out double expectedCosine);

            Assert.Equal(BitConverter.DoubleToInt64Bits(expectedSine), BitConverter.DoubleToInt64Bits(sine));
            Assert.Equal(BitConverter.DoubleToInt64Bits(expectedCosine), BitConverter.DoubleToInt64Bits(cosine));
        }

        [Fact]
        public void QuarterTurnsAreExact() {
            AssertSinCos(0, 0.0, 1.0);
            AssertSinCos(90, 1.0, 0.0);
            AssertSinCos(180, 0.0, -1.0);
            AssertSinCos(270, -1.0, 0.0);
            AssertSinCos(-90, -1.0, 0.0);
        }

        [Fact]
        public void TableStaysWithinItsRoundingOfTrueSine() {
            for (int degrees = 0; degrees < 360; degrees++) {
                DegreeSine.SinCos(degrees, out double sine, out double cosine);
                double radians = degrees * Math.PI / 180.0;
                Assert.InRange(Math.Abs(sine - Math.Sin(radians)), 0.0, 5.0001e-8);
                Assert.InRange(Math.Abs(cosine - Math.Cos(radians)), 0.0, 5.0001e-8);
            }
        }

        private static void AssertSinCos(int degrees, double expectedSine, double expectedCosine) {
            DegreeSine.SinCos(degrees, out double sine, out double cosine);
            Assert.Equal(expectedSine, sine);
            Assert.Equal(expectedCosine, cosine);
        }
